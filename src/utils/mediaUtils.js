export const getRandomPhoto = () => BHUNTU_PHOTOS[Math.floor(Math.random() * BHUNTU_PHOTOS.length)];

// Dynamic image error handler cycling through all 167 photos with unique fallback seed
export const handlePhotoError = (e, seed) => {
  if (!e || !e.target) return;
  let index = typeof seed === 'number' ? seed : null;

  if (index === null) {
    const srcStr = e.target.getAttribute('src') || '';
    const numMatches = srcStr.match(/\d+/g);
    if (numMatches && numMatches.length > 0) {
      index = parseInt(numMatches[numMatches.length - 1], 10);
    } else {
      index = Math.floor(Math.random() * ALL_PHOTOS.length);
    }
  }

  const idx = Math.abs(index % ALL_PHOTOS.length);
  const fallbackPath = ALL_PHOTOS[idx] || ALL_PHOTOS[0];
  const targetUrl = getAssetUrl(fallbackPath);

  if (e.target.src !== targetUrl && !e.target.dataset.failed) {
    e.target.dataset.failed = 'true';
    e.target.src = targetUrl;
  }
};

