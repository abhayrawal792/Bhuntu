/**
 * Cleanly formats asset path with BASE_URL support (defaulting to relative clean path)
 */
export const getAssetUrl = (path) => {
  if (!path) return getAssetUrl(ALL_PHOTOS[0]);
  if (path.startsWith('http://') || path.startsWith('https://')) return path;

  // Map legacy 'photos/photoX.jpg' paths to ALL_PHOTOS[(X - 1) % ALL_PHOTOS.length]
  const photoMatch = path.match(/photos\/photo(\d+)\.(jpg|png|jpeg)/i);
  if (photoMatch) {
    const num = parseInt(photoMatch[1], 10) - 1;
    const mapped = ALL_PHOTOS[num % ALL_PHOTOS.length];
    if (mapped) path = mapped;
  }

  const clean = path.replace(/^(\.\/|\/)/, '');
  let base = import.meta.env.BASE_URL || '/';

  if (base === '/' || base === './' || base === '') {
    return `/${clean}`;
  }

  if (!base.endsWith('/')) base += '/';
  if (!clean.startsWith(base.replace(/^\//, ''))) {
    return `${base}${clean}`;
  }
  return clean.startsWith('/') ? clean : `/${clean}`;
};

